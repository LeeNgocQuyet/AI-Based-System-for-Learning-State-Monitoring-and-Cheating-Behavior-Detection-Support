-- Group 3 Learning Monitoring System
-- PostgreSQL 15+ | Auth, RBAC, sessions and events schema v1
-- Apply once to an empty database. Future changes should be delivered as migrations.

BEGIN;

-- ----- ENUM TYPES -----------------------------------------------------------
CREATE TYPE user_role AS ENUM ('LEARNER', 'INSTRUCTOR');
CREATE TYPE account_status AS ENUM ('ACTIVE', 'DISABLED');
CREATE TYPE session_type AS ENUM ('LEARNING', 'EXAM');
CREATE TYPE session_status AS ENUM ('ACTIVE', 'PAUSED', 'ENDED');
CREATE TYPE event_type AS ENUM (
    'EYES_CLOSED_LONG',
    'YAWN_DETECTED',
    'HEAD_NOD_DETECTED',
    'LOOK_AWAY_DETECTED',
    'FACE_NOT_DETECTED',
    'MULTIPLE_FACES_DETECTED',
    'PHONE_DETECTED',
    'TAB_HIDDEN',
    'CAMERA_LOST',
    'CONNECTION_LOST'
);
CREATE TYPE event_source AS ENUM ('AI_LEARNING', 'AI_EXAM', 'BROWSER', 'SYSTEM');
CREATE TYPE event_severity AS ENUM ('INFO', 'LOW', 'MEDIUM', 'HIGH');

-- ----- USERS ----------------------------------------------------------------
CREATE TABLE users (
    user_id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email           VARCHAR(320) NOT NULL,
    full_name       VARCHAR(120) NOT NULL,
    password_hash   TEXT NOT NULL,
    role            user_role NOT NULL DEFAULT 'LEARNER',
    status          account_status NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_users_email_lowercase CHECK (email = LOWER(email)),
    CONSTRAINT ck_users_full_name_nonempty CHECK (LENGTH(TRIM(full_name)) > 0)
);
CREATE UNIQUE INDEX uq_users_email_ci ON users (LOWER(email));
CREATE INDEX ix_users_role_status ON users (role, status);

-- ----- SESSIONS -------------------------------------------------------------
-- A session starts in ACTIVE state. Backend updates accumulated_active_ms
-- whenever it pauses or ends a session. Paused time is excluded from duration.
-- EXAM sessions cannot be paused under any circumstances.
CREATE TABLE sessions (
    session_id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    learner_id              UUID NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    session_type            session_type NOT NULL,
    status                  session_status NOT NULL DEFAULT 'ACTIVE',
    started_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    paused_at               TIMESTAMPTZ NULL,
    ended_at                TIMESTAMPTZ NULL,
    active_started_at       TIMESTAMPTZ NULL,
    accumulated_active_ms   BIGINT NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_sessions_duration_nonnegative CHECK (accumulated_active_ms >= 0),
    CONSTRAINT ck_sessions_exam_no_pause CHECK (session_type <> 'EXAM' OR status <> 'PAUSED'),
    CONSTRAINT ck_sessions_state_timestamps CHECK (
        (status = 'ACTIVE' AND active_started_at IS NOT NULL AND paused_at IS NULL AND ended_at IS NULL)
        OR
        (status = 'PAUSED' AND active_started_at IS NULL AND paused_at IS NOT NULL AND ended_at IS NULL)
        OR
        (status = 'ENDED' AND active_started_at IS NULL AND paused_at IS NULL AND ended_at IS NOT NULL)
    ),
    CONSTRAINT ck_sessions_end_after_start CHECK (ended_at IS NULL OR ended_at >= started_at)
);
CREATE INDEX ix_sessions_learner_started ON sessions (learner_id, started_at DESC);
CREATE INDEX ix_sessions_status_started ON sessions (status, started_at DESC);
CREATE INDEX ix_sessions_type_status ON sessions (session_type, status);

-- Automatically set active_started_at when inserting an ACTIVE session without explicit active_started_at.
-- Leave active_started_at NULL for PAUSED and ENDED sessions.
CREATE FUNCTION init_session_active_timestamp() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 'ACTIVE' AND NEW.active_started_at IS NULL THEN
        NEW.active_started_at := COALESCE(NEW.started_at, NOW());
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_session_init_active_timestamp
BEFORE INSERT ON sessions
FOR EACH ROW EXECUTE FUNCTION init_session_active_timestamp();

-- Ensure that only an active LEARNER account can own a session.
CREATE FUNCTION enforce_learner_session_owner() RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM users
        WHERE user_id = NEW.learner_id
          AND role = 'LEARNER'
          AND status = 'ACTIVE'
    ) THEN
        RAISE EXCEPTION 'sessions.learner_id must reference an active LEARNER account'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_session_learner_role
BEFORE INSERT OR UPDATE OF learner_id ON sessions
FOR EACH ROW EXECUTE FUNCTION enforce_learner_session_owner();

-- ----- EVENTS ---------------------------------------------------------------
-- event_id is generated by the producer once and reused for retries.
-- Backend must validate producer identity/source before inserting.
CREATE TABLE events (
    event_id          UUID PRIMARY KEY,
    session_id        UUID NOT NULL REFERENCES sessions(session_id) ON DELETE RESTRICT,
    schema_version    VARCHAR(32) NOT NULL DEFAULT '1.0.0',
    event_type        event_type NOT NULL,
    occurred_at       TIMESTAMPTZ NOT NULL,
    received_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    source            event_source NOT NULL,
    severity          event_severity NOT NULL,
    duration_ms       BIGINT NULL,
    confidence        NUMERIC(5,4) NULL,
    message           VARCHAR(500) NOT NULL,
    is_reviewed       BOOLEAN NOT NULL DEFAULT FALSE,
    reviewed_at       TIMESTAMPTZ NULL,
    metadata          JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT ck_events_schema_version CHECK (schema_version = '1.0.0'),
    CONSTRAINT ck_events_duration_nonnegative CHECK (duration_ms IS NULL OR duration_ms >= 0),
    CONSTRAINT ck_events_confidence_range CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
    CONSTRAINT ck_events_metadata_object CHECK (JSONB_TYPEOF(metadata) = 'object'),
    CONSTRAINT ck_events_source_matches_type CHECK (
        (event_type IN ('EYES_CLOSED_LONG', 'YAWN_DETECTED', 'HEAD_NOD_DETECTED') AND source = 'AI_LEARNING')
        OR
        (event_type IN ('LOOK_AWAY_DETECTED', 'FACE_NOT_DETECTED') AND source IN ('AI_LEARNING', 'AI_EXAM'))
        OR
        (event_type IN ('MULTIPLE_FACES_DETECTED', 'PHONE_DETECTED') AND source = 'AI_EXAM')
        OR
        (event_type = 'TAB_HIDDEN' AND source = 'BROWSER')
        OR
        (event_type = 'CAMERA_LOST' AND source = 'BROWSER')
        OR
        (event_type = 'CONNECTION_LOST' AND source = 'SYSTEM')
    )
);
CREATE INDEX ix_events_session_occurred ON events (session_id, occurred_at DESC, received_at DESC);
CREATE INDEX ix_events_session_severity ON events (session_id, severity);
CREATE INDEX ix_events_session_reviewed ON events (session_id, is_reviewed);
CREATE INDEX ix_events_type_occurred ON events (event_type, occurred_at DESC);

-- ----- INSTRUCTOR ACCESS ----------------------------------------------------
-- Explicit allow-list: an instructor can read a session only when a row exists.
-- Rows are created by trusted provisioning/admin workflow, never by learners.
CREATE TABLE instructor_session_access (
    instructor_id   UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    session_id      UUID NOT NULL REFERENCES sessions(session_id) ON DELETE CASCADE,
    granted_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (instructor_id, session_id)
);
CREATE INDEX ix_instructor_access_session ON instructor_session_access (session_id);

-- Enforce that the account receiving the grant is actually an instructor.
CREATE FUNCTION enforce_instructor_access_role() RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM users
        WHERE user_id = NEW.instructor_id
          AND role = 'INSTRUCTOR'
          AND status = 'ACTIVE'
    ) THEN
        RAISE EXCEPTION 'instructor_session_access requires an active INSTRUCTOR account'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_instructor_access_role
BEFORE INSERT OR UPDATE OF instructor_id ON instructor_session_access
FOR EACH ROW EXECUTE FUNCTION enforce_instructor_access_role();

-- Remove grants when an instructor is disabled or demoted.
CREATE FUNCTION revoke_instructor_grants_on_role_change() RETURNS TRIGGER AS $$
BEGIN
    IF NEW.role <> 'INSTRUCTOR' OR NEW.status <> 'ACTIVE' THEN
        DELETE FROM instructor_session_access WHERE instructor_id = NEW.user_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_revoke_instructor_grants
AFTER UPDATE OF role, status ON users
FOR EACH ROW EXECUTE FUNCTION revoke_instructor_grants_on_role_change();

-- ----- REFRESH TOKENS -------------------------------------------------------
-- Store only SHA-256 hashes of opaque refresh tokens, never raw token values.
CREATE TABLE refresh_tokens (
    token_id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash      BYTEA NOT NULL UNIQUE,
    expires_at      TIMESTAMPTZ NOT NULL,
    revoked_at      TIMESTAMPTZ NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_agent      VARCHAR(500) NULL,
    CONSTRAINT ck_refresh_token_hash_length CHECK (OCTET_LENGTH(token_hash) = 32),
    CONSTRAINT ck_refresh_token_expiry CHECK (expires_at > created_at)
);
CREATE INDEX ix_refresh_tokens_user_active ON refresh_tokens (user_id, expires_at)
    WHERE revoked_at IS NULL;

-- ----- UPDATED_AT TRIGGERS --------------------------------------------------
CREATE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_sessions_updated_at
BEFORE UPDATE ON sessions
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;

